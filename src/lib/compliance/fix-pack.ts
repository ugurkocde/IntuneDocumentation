// Draft Windows Settings Catalog policies for capabilities whose setting is
// not in place. The app never writes them to a tenant: the admin imports the
// files (Devices > Manage devices > Configuration > Create > Import policy).
// Only choice settings whose definition and option ids are in the verified
// settings files are emitted. Everything else is listed as not generatable.
// The document shape was verified in the lab tenant on 2026-10-18 by creating
// an unassigned policy through Graph beta, reading it back and deleting it.

/** One Settings Catalog choice setting, as Graph returns it with $expand=settings. */
export interface FixPackChoiceSettingInstance {
  "@odata.type": "#microsoft.graph.deviceManagementConfigurationChoiceSettingInstance";
  settingDefinitionId: string;
  choiceSettingValue: {
    value: string;
    children: FixPackChoiceSettingInstance[];
  };
}

/** Body of POST /beta/deviceManagement/configurationPolicies, never with assignments. */
export interface FixPackPolicyDocument {
  name: string;
  description: string;
  platforms: "windows10";
  technologies: "mdm";
  roleScopeTagIds: string[];
  templateReference: { templateId: ""; templateFamily: "none" };
  settings: Array<{
    "@odata.type": "#microsoft.graph.deviceManagementConfigurationSetting";
    settingInstance: FixPackChoiceSettingInstance;
  }>;
}

export interface FixPackPolicy {
  fileName: string;
  capabilityId: string;
  /** "<framework id>:<control id>" for every assessed control the capability supports. */
  controlIds: string[];
  json: FixPackPolicyDocument;
  /** Alternative settings left out of this policy, with the reason. */
  notes: string[];
}

export interface FixPackGap {
  capabilityId: string;
  name: string;
  reason: string;
}

export interface FixPack {
  policies: FixPackPolicy[];
  notGeneratable: FixPackGap[];
  summary: { draftPolicies: number; notGeneratable: number };
}

export interface FixPackOptions {
  /** Restrict the pack to capabilities mapped to this framework's controls. */
  frameworkId?: string;
  /**
   * The collection the assessment was made from. Required: a policy that
   * sets the parent of a missing child setting to another option leaves no
   * check in the assessment, so only the collection shows that deliberate
   * choice, and without it a draft would overrule that choice.
   */
  collection: ComplianceExportData;
}

export const FIX_PACK_POLICY_PREFIX = "Intune Documentation fix pack: ";

/**
 * Microsoft documents no maximum description length for configuration
 * policies (Graph docs and Microsoft Learn, checked 18 October 2026), so a
 * draft stays within a conservative 1000 characters. The README lists every
 * control.
 */
export const FIX_PACK_DESCRIPTION_MAX = 1000;

/** The fixed text plus as many control ids as fit, never cutting the warning. */
function draftDescription(fixed: string, controls: readonly string[]): string {
  if (!controls.length) return `${fixed} Controls: none mapped.`;
  for (let shown = controls.length; shown > 0; shown--) {
    const rest = controls.length - shown;
    const text = `${fixed} Controls: ${controls.slice(0, shown).join(", ")}${rest ? `, and ${rest} more in README.txt` : ""}.`;
    if (text.length <= FIX_PACK_DESCRIPTION_MAX) return text;
  }
  return `${fixed} Controls: ${controls.length} supported, listed in README.txt.`;
}

export const FIX_PACK_WARNING =
  "Draft generated by Intune Documentation from missing evidence. It is unassigned and has no effect until you assign it. It may duplicate settings delivered by other means, such as Group Policy, security baselines or other profiles, and cause conflicts. Review every setting before import and do not import it blindly. Assign it to a pilot group first and to further groups only after testing.";

const definitions = [...verified.catalog, ...additionalVerified.catalog];
const definitionById = new Map(definitions.map((row) => [row.id, row]));

const PLATFORM_LABELS: Record<CompliancePlatform, string> = {
  windows: "Windows",
  macos: "macOS",
  ios: "iOS/iPadOS",
  android: "Android",
  tenant: "tenant-wide",
};

// A UEFI lock cannot be removed remotely, so a draft never selects it.
const UEFI_LOCK = /\bwith UEFI lock\b/i;

// Only "noEvidence" is generated, and only when every check ran on a complete
// collection and reported the setting as missing (see blocker()). Any other
// state means an existing policy, not a new one, is the fix. Capabilities in
// place or outside the assessed scope are not reported at all.
const SKIPPED_STATUSES: ReadonlySet<CapabilityStatus> = new Set([
  "enforced",
  "requirementAssigned",
  "notApplicable",
]);
const STATUS_REASONS: Partial<Record<CapabilityStatus, string>> = {
  configuredNotAssigned:
    "Setting exists in an unassigned policy; assign that policy instead.",
  partialConfiguration:
    "Some required settings are already on an assigned policy. Complete that policy instead of importing a second one.",
  disabledByPolicy:
    "A policy explicitly sets a non-enforcing value. Change that policy, because a second policy with the opposite value conflicts on devices.",
  conflictingEvidence:
    "Assigned policies contain both enforcing and non-enforcing values. Resolve the conflict in the existing policies.",
  assignmentUnknown:
    "Assignment data could not be read, so the setting may already be in place. Refresh the policies and generate the pack again.",
  collectionIncomplete:
    "Policy collection was incomplete, so the setting may already be in place. Refresh the policies and generate the pack again.",
};

interface SettingPath {
  /** Root first; the last entry is the signal's own setting. */
  entries: Array<{ id: string; value: string }>;
}

type Resolution =
  | { ok: true; path: SettingPath }
  | { ok: false; reason: string };

function unsupportedReason(signal: DetectionSignal): string {
  switch (signal.source) {
    case "graphProperty":
      return "Detected through a template or compliance policy property, not a Settings Catalog setting.";
    case "policyCheck":
      return "Detected through a policy check that needs tenant-specific values or design decisions.";
    case "administrativeTemplate":
      return "Detected through an administrative template, which the fix pack does not generate.";
    case "securityBaseline":
      return "Detected through a security baseline, which the fix pack does not generate.";
    case "omaUri":
      return "Detected through a custom OMA-URI setting, which the fix pack does not generate.";
    case "tenantPolicy":
      return "Entra setting, change it in the Entra admin center.";
    default:
      return "The setting has no verified Settings Catalog choice value.";
  }
}

function parentsOf(id: string) {
  return definitions.flatMap((row) =>
    row.options
      .filter((option) => option.children.includes(id))
      .map((option) => ({ id: row.id, value: option.id })),
  );
}

function resolveSignal(signal: DetectionSignal): Resolution {
  if (signal.source !== "settingsCatalog")
    return { ok: false, reason: unsupportedReason(signal) };
  const id = signal.settingDefinitionId;
  const definition = definitionById.get(id);
  if (!definition)
    return {
      ok: false,
      reason: `Setting ${id} has no verified definition in this build.`,
    };
  if (!definition.options.length)
    return {
      ok: false,
      reason: `Setting ${id} takes a simple or list value, not a verified choice option.`,
    };
  const expected = signal.enforcedWhen;
  const candidates =
    expected.kind === "equals"
      ? [expected.value]
      : expected.kind === "oneOf"
        ? [...expected.values]
        : [];
  const options = candidates
    .map((value) => definition.options.find((option) => option.id === value))
    .filter((option) => option !== undefined);
  if (!options.length)
    return {
      ok: false,
      reason: `The enforcing value of ${id} is not a verified choice option.`,
    };
  const option = options.find((row) => !UEFI_LOCK.test(row.label));
  if (!option)
    return {
      ok: false,
      reason: `Every enforcing option of ${id} sets a UEFI lock, which cannot be removed remotely. Configure it deliberately.`,
    };

  const entries = [{ id, value: option.id }];
  for (let child = id; ; ) {
    const parents = parentsOf(child);
    if (!parents.length) break;
    if (parents.length > 1 || entries.length > 8)
      return {
        ok: false,
        reason: `The parent setting of ${child} is ambiguous in the verified definitions.`,
      };
    entries.unshift(parents[0]!);
    child = parents[0]!.id;
  }
  const consistent = (signal.prerequisites ?? []).every((required) =>
    entries.some(
      (entry) =>
        entry.id === required.settingDefinitionId &&
        required.values.includes(entry.value),
    ),
  );
  if (!consistent)
    return {
      ok: false,
      reason: `The declared parent setting of ${id} does not match the verified definitions.`,
    };
  return { ok: true, path: { entries } };
}

/** Why a path leaves out child settings its options need, if it does. */
function missingChildren(
  path: SettingPath,
  present: ReadonlySet<string>,
): string | undefined {
  for (const entry of path.entries) {
    const definition = definitionById.get(entry.id);
    const option = definition?.options.find((row) => row.id === entry.value);
    const missing = (option?.children ?? []).filter((id) => !present.has(id));
    if (definition && missing.length)
      return `${definition.name} needs ${missing.length} dependent ${missing.length === 1 ? "setting" : "settings"} with no verified value in this build, and a draft never sends it without ${missing.length === 1 ? "it" : "them"}. Configure it manually.`;
  }
  return undefined;
}

function optionLabel(id: string, value: unknown): string {
  const option = definitionById
    .get(id)
    ?.options.find((row) => row.id === String(value));
  return option ? `"${option.label}"` : JSON.stringify(value);
}

type ConfiguredValues = Map<
  string,
  Array<{ policyName: string; values: unknown[] }>
>;

/** Every Settings Catalog value the collected policies configure. */
function configuredValues(collection: ComplianceExportData): ConfiguredValues {
  const configured: ConfiguredValues = new Map();
  for (const config of collectConfigurations(collection)) {
    const policyName = String(
      config.displayName || config.name || "Unnamed policy",
    );
    for (const [id, values] of collectCatalogValues(config.settings)) {
      const rows = configured.get(id) ?? [];
      rows.push({ policyName, values });
      configured.set(id, rows);
    }
  }
  return configured;
}

/**
 * A collected policy that sets a setting of the draft, typically the parent
 * of the missing child, to another option made a deliberate choice. The
 * assessment holds no check for a child under a disabled parent.
 */
function deliberateChoice(
  paths: readonly SettingPath[],
  configured: ConfiguredValues,
): string | undefined {
  for (const path of paths)
    for (const entry of path.entries)
      for (const row of configured.get(entry.id) ?? []) {
        const other = row.values.find((value) => String(value) !== entry.value);
        if (row.values.length && other === undefined) continue;
        const name = definitionById.get(entry.id)?.name ?? entry.id;
        return `The policy "${row.policyName}" sets ${name} to ${other === undefined ? "a value that could not be read" : optionLabel(entry.id, other)}, so the setting is deliberately configured differently. Change that policy instead of importing a draft.`;
      }
  return undefined;
}

function buildSettings(
  paths: readonly SettingPath[],
): FixPackPolicyDocument["settings"] {
  const roots: FixPackChoiceSettingInstance[] = [];
  for (const path of paths) {
    let level = roots;
    for (const entry of path.entries) {
      let instance = level.find((row) => row.settingDefinitionId === entry.id);
      if (!instance) {
        instance = {
          "@odata.type":
            "#microsoft.graph.deviceManagementConfigurationChoiceSettingInstance",
          settingDefinitionId: entry.id,
          choiceSettingValue: { value: entry.value, children: [] },
        };
        level.push(instance);
      }
      level = instance.choiceSettingValue.children;
    }
  }
  return roots.map((settingInstance) => ({
    "@odata.type": "#microsoft.graph.deviceManagementConfigurationSetting",
    settingInstance,
  }));
}

interface Selection {
  paths: SettingPath[];
  omitted: string[];
}

function selectSettings(
  result: CapabilityResult,
  chosen: ReadonlyMap<string, { value: string; capability: string }>,
): Selection | { reason: string } {
  const { capability } = result;
  const groups = capability.requiredGroups ?? [];
  const resolved = capability.signals
    .filter(
      (signal) =>
        !groups.length ||
        (signal.requirementGroup !== undefined &&
          groups.includes(signal.requirementGroup)),
    )
    .map((signal) => ({ signal, resolution: resolveSignal(signal) }));

  let candidates = resolved.flatMap(({ signal, resolution }) =>
    resolution.ok ? [{ signal, path: resolution.path }] : [],
  );
  // Device scope applies regardless of who signs in, so it replaces an
  // identical user-scoped setting.
  const ids = new Set(candidates.map(({ path }) => path.entries.at(-1)!.id));
  candidates = candidates.filter(({ path }) => {
    const id = path.entries.at(-1)!.id;
    return !(id.startsWith("user_") && ids.has(`device_${id.slice(5)}`));
  });

  const owners = new Map<string, number>();
  const local = new Map<string, string>();
  const paths: Array<{ signal: DetectionSignal; path: SettingPath }> = [];
  for (const candidate of candidates) {
    const clash = candidate.path.entries.find((entry) => {
      const value = local.get(entry.id) ?? chosen.get(entry.id)?.value;
      return value !== undefined && value !== entry.value;
    });
    if (clash) {
      const owner = chosen.get(clash.id)?.capability ?? capability.id;
      owners.set(owner, (owners.get(owner) ?? 0) + 1);
      continue;
    }
    for (const entry of candidate.path.entries)
      local.set(entry.id, entry.value);
    paths.push(candidate);
  }

  // An option whose definition lists child settings is only sent with all of
  // them, never with children: [], so a path is dropped until every option
  // left in the policy has its children in the policy too.
  const incomplete = new Set<string>();
  for (;;) {
    const present = new Set(
      paths.flatMap(({ path }) => path.entries.map((entry) => entry.id)),
    );
    const reasons = paths.map(({ path }) => missingChildren(path, present));
    if (!reasons.some(Boolean)) break;
    for (let index = paths.length - 1; index >= 0; index -= 1)
      if (reasons[index]) {
        incomplete.add(reasons[index]!);
        paths.splice(index, 1);
      }
  }

  const omitted = [
    ...[...owners].map(
      ([owner, count]) =>
        `${count} alternative ${count === 1 ? "setting is" : "settings are"} left out because the ${owner} policy in this pack sets ${count === 1 ? "it" : "them"} to a different value.`,
    ),
    ...incomplete,
  ];
  const missingGroups = groups.filter(
    (group) => !paths.some(({ signal }) => signal.requirementGroup === group),
  );
  if (!paths.length || missingGroups.length) {
    const reasons = [
      ...new Set(
        resolved.flatMap(({ resolution }) =>
          resolution.ok ? [] : [resolution.reason],
        ),
      ),
      ...omitted,
    ];
    return {
      reason: [
        ...(missingGroups.length
          ? [
              `Required setting groups ${missingGroups.join(", ")} cannot be generated together in one policy.`,
            ]
          : []),
        ...reasons,
      ].join(" "),
    };
  }
  return { paths: paths.map(({ path }) => path), omitted };
}

/** Why a capability gets no draft, or null when a draft may be generated. */
function blocker(result: CapabilityResult): string | null {
  const { status, checks } = result;
  if (status !== "noEvidence")
    return STATUS_REASONS[status] ?? `Status ${status} is not generated.`;
  if (checks.some((check) => check.result === "different"))
    return "A policy sets this setting to a different value. Change that policy instead of importing a second one.";
  if (
    result.evidence.length ||
    !checks.length ||
    checks.some(
      (check) =>
        check.assessmentStatus !== "checked" || check.result !== "missing",
    )
  )
    return "The collection could not establish that the setting is missing. Refresh the policies with a complete collection and generate the pack again.";
  return null;
}

export function generateFixPack(
  assessment: ComplianceAssessment,
  options: FixPackOptions,
): FixPack {
  // Also guards untyped callers: never generate without the collection.
  if (!options?.collection)
    throw new Error(
      "A fix pack needs the collection the assessment was made from.",
    );
  const frameworks = assessment.frameworks.filter(
    (row) => !options.frameworkId || row.framework.id === options.frameworkId,
  );
  const controlIds = (capabilityId: string) =>
    frameworks.flatMap((row) =>
      row.controls
        .filter((control) => control.capabilityIds.includes(capabilityId))
        .map((control) => `${row.framework.id}:${control.control.id}`),
    );
  const chosen = new Map<string, { value: string; capability: string }>();
  const configured = configuredValues(options.collection);
  const drafts: Array<{
    result: CapabilityResult;
    controls: string[];
    paths: SettingPath[];
    notes: string[];
  }> = [];
  const notGeneratable: FixPackGap[] = [];
  const gapFor = (result: CapabilityResult, reason: string) =>
    notGeneratable.push({
      capabilityId: result.capability.id,
      name: result.capability.name,
      reason,
    });

  for (const result of assessment.capabilities) {
    const { capability, status } = result;
    const controls = controlIds(capability.id);
    if (options.frameworkId && !controls.length) continue;
    if (SKIPPED_STATUSES.has(status)) continue;
    // No draft while an alternative is in use or unreadable, or the setting
    // cannot be combined with Conditional Access (README "Alternative
    // capabilities"), so it is neither a draft nor listed.
    if (result.alternative) continue;
    const gap = (reason: string) => gapFor(result, reason);
    const blocked = blocker(result);
    if (blocked) {
      gap(blocked);
      continue;
    }
    if (capability.platform !== "windows") {
      const entra = capability.signals.find(
        (signal) => signal.source === "tenantPolicy",
      );
      gap(
        entra
          ? unsupportedReason(entra)
          : `The fix pack covers Windows Settings Catalog settings only. Configure this ${PLATFORM_LABELS[capability.platform]} capability manually.`,
      );
      continue;
    }
    const selection = selectSettings(result, chosen);
    if ("reason" in selection) {
      gap(selection.reason);
      continue;
    }
    const deliberate = deliberateChoice(selection.paths, configured);
    if (deliberate) {
      gap(deliberate);
      continue;
    }
    for (const path of selection.paths)
      for (const entry of path.entries)
        chosen.set(entry.id, { value: entry.value, capability: capability.id });
    drafts.push({
      result,
      controls,
      paths: selection.paths,
      notes: selection.omitted,
    });
  }

  // Umbrella capabilities reuse the settings of their component capabilities.
  // Smaller drafts claim their settings first; a draft whose settings are all
  // claimed is left out, and otherwise only shares settings when it needs
  // them together for its required groups.
  const leaf = (path: SettingPath) => path.entries.at(-1)!.id;
  const owner = new Map<string, string>();
  const kept = new Set<(typeof drafts)[number]>();
  for (const draft of [...drafts].sort(
    (left, right) => left.paths.length - right.paths.length,
  )) {
    const covered = draft.paths.filter((path) => owner.has(leaf(path)));
    const owners = [...new Set(covered.map((path) => owner.get(leaf(path))!))];
    const drafted = `${owners.length === 1 ? "draft" : "drafts"} for ${owners.join(", ")} in this pack`;
    if (covered.length === draft.paths.length) {
      gapFor(
        draft.result,
        `Every setting of this capability is already in the ${drafted}, so it gets no separate draft.`,
      );
      continue;
    }
    const rest = draft.paths.filter((path) => !covered.includes(path));
    const present = new Set(
      rest.flatMap((path) => path.entries.map((entry) => entry.id)),
    );
    // Stripping must not leave an option without the children it needs.
    if (
      covered.length &&
      !draft.result.capability.requiredGroups?.length &&
      !rest.some((path) => missingChildren(path, present))
    ) {
      draft.paths = rest;
      draft.notes.push(
        `${covered.length} ${covered.length === 1 ? "setting is" : "settings are"} left out because the ${drafted} already ${covered.length === 1 ? "contains it" : "contain them"}.`,
      );
    }
    for (const path of draft.paths)
      if (!owner.has(leaf(path)))
        owner.set(leaf(path), draft.result.capability.id);
    kept.add(draft);
  }

  const policies = drafts
    .filter((draft) => kept.has(draft))
    .map(
      (
        { result: { capability }, controls, paths, notes },
        index,
      ): FixPackPolicy => ({
        fileName: `${String(index + 1).padStart(2, "0")}-${capability.id}.json`,
        capabilityId: capability.id,
        controlIds: controls,
        json: {
          name: `${FIX_PACK_POLICY_PREFIX}${capability.name} (draft, unassigned)`,
          description: draftDescription(
            [
              FIX_PACK_WARNING,
              `Generated ${assessment.generatedAt} with ruleset ${assessment.provenance.rulesetVersion}.`,
              `Capability: ${capability.id}.`,
            ].join(" "),
            controls,
          ),
          platforms: "windows10",
          technologies: "mdm",
          roleScopeTagIds: ["0"],
          templateReference: { templateId: "", templateFamily: "none" },
          settings: buildSettings(paths),
        },
        notes,
      }),
    );
  return {
    policies,
    notGeneratable,
    summary: {
      draftPolicies: policies.length,
      notGeneratable: notGeneratable.length,
    },
  };
}

export function fixPackReadme(
  pack: FixPack,
  assessment: Pick<ComplianceAssessment, "generatedAt" | "provenance">,
): string {
  const list = (rows: string[], empty: string) =>
    rows.length ? rows.map((row) => `- ${row}`) : [empty];
  return [
    "Intune Documentation fix pack",
    "",
    "What this is",
    "Each JSON file in this pack is a draft Windows Settings Catalog policy for settings that the evidence assessment did not find in place. Intune Documentation never writes to your tenant. You decide what to import.",
    "",
    "Important",
    "- Every policy is a draft generated from missing evidence. It is unassigned and has no effect on any device or user until you assign it.",
    "- A setting can be missing from the evidence and still be delivered by other means, such as Group Policy, security baselines or other profiles. Importing a duplicate can cause conflicts.",
    "- Review every setting before import and do not import blindly. The values follow the evidence rules, not your organisation's requirements, exceptions or change process.",
    "- Check for overlap with existing policies. Two policies that set the same setting to different values conflict on devices.",
    "- Settings that set a UEFI lock are never generated, because the lock cannot be removed remotely.",
    "- Assign each policy to a pilot group first and widen the assignment after testing.",
    "",
    "How to import a policy",
    "1. Sign in to the Microsoft Intune admin center (https://intune.microsoft.com).",
    "2. Go to Devices > Manage devices > Configuration.",
    "3. Select Create > Import policy.",
    "4. Select one JSON file from this pack, enter a name for the new policy and select Save.",
    "5. Open the new policy and review its settings. Assign it to a pilot group when you are ready.",
    "Repeat these steps for each file.",
    "",
    "Policies in this pack",
    ...list(
      pack.policies.map((policy) =>
        [
          `${policy.fileName}: ${policy.json.name}. Capability ${policy.capabilityId}.`,
          policy.controlIds.length
            ? `Supports ${policy.controlIds.join(", ")}.`
            : "",
          ...policy.notes,
        ]
          .filter(Boolean)
          .join(" "),
      ),
      "None. No missing Windows Settings Catalog setting could be generated.",
    ),
    "",
    `Summary: ${pack.summary.draftPolicies} draft policies, ${pack.summary.notGeneratable} not generatable.`,
    "",
    "Not generated",
    "These items need manual configuration or a change to an existing policy.",
    ...list(
      pack.notGeneratable.map(
        (row) => `${row.name} (${row.capabilityId}): ${row.reason}`,
      ),
      "None.",
    ),
    "",
    `Ruleset ${assessment.provenance.rulesetVersion}, assessment generated ${assessment.generatedAt}.`,
    COMPLIANCE_DISCLAIMER,
    "",
  ].join("\r\n");
}

/** ZIP with one JSON file per policy and README.txt. */
export async function buildFixPackZip(
  pack: FixPack,
  assessment: Pick<ComplianceAssessment, "generatedAt" | "provenance">,
): Promise<Uint8Array> {
  const zip = new JSZip();
  // A fixed date keeps the archive byte-identical for the same input.
  const date = new Date("2026-01-01T00:00:00Z");
  zip.file("README.txt", fixPackReadme(pack, assessment), { date });
  for (const policy of pack.policies)
    zip.file(policy.fileName, `${JSON.stringify(policy.json, null, 2)}\n`, {
      date,
    });
  return zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
}
